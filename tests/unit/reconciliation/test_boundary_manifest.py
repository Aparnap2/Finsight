"""Guard the reconciliation runtime boundary against silent drift.

``docs/release/reconciliation-boundary.json`` is generated by
``scripts/reconciliation_boundary.py``. This test recomputes the boundary and
compares it with the committed manifest, so a module entering or leaving the
runtime is a reviewed change instead of an accident.
"""

from __future__ import annotations

import importlib.util
import json
from pathlib import Path
from types import ModuleType
from typing import Any

_ROOT = Path(__file__).resolve().parents[3]
_SCRIPT = _ROOT / "scripts" / "reconciliation_boundary.py"
_MANIFEST = _ROOT / "docs" / "release" / "reconciliation-boundary.json"


def _load_script() -> ModuleType:
    spec = importlib.util.spec_from_file_location("reconciliation_boundary", _SCRIPT)
    assert spec is not None
    assert spec.loader is not None
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


def _computed() -> dict[str, Any]:
    boundary: dict[str, Any] = _load_script().compute_boundary()
    return boundary


def test_committed_manifest_matches_the_code() -> None:
    """The committed manifest must equal the current import closure."""
    committed = json.loads(_MANIFEST.read_text(encoding="utf-8"))
    assert _computed() == committed, (
        "reconciliation boundary drifted. Regenerate with "
        "`python scripts/reconciliation_boundary.py "
        "--out docs/release/reconciliation-boundary.json` "
        "and state in the commit message why a module entered or left the runtime."
    )


def test_boundary_stays_confined_to_the_engine() -> None:
    """The demo path must not quietly pull in the web app or a third-party SDK."""
    boundary = _computed()
    assert boundary["third_party_imports"] == []
    for path in boundary["files"]:
        assert path == "finance/__init__.py" or path.startswith("finance/reconciliation/"), path
    for path in boundary["fixtures"]:
        assert (_ROOT / path).is_file(), path
